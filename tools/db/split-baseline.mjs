// One-off generator for the Durable Object schema baselines (docs/multi-user.md 5.7): applies the D1 migrations
// 0001–0009 to an empty SQLite database and writes each object's starting schema from the result.
//   packages/db/directory-migrations/0001_baseline.sql   users, sign-in, account usage
//   packages/db/budget-migrations/0001_baseline.sql      everything about one budget
// The output is committed; rerunning must reproduce it byte for byte (tools/ci/migration-check.mjs checks this).
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const SRC = 'packages/db/migrations';
const UPTO = '0009';
const DIRECTORY = new Set([
  'user',
  'budget_member',
  'passkey',
  'auth_session',
  'auth_challenge',
  'device_link',
  'usage_day',
]);

const db = new DatabaseSync(':memory:');
for (const f of readdirSync(SRC)
  .filter((f) => f.endsWith('.sql') && f.slice(0, 4) <= UPTO)
  .sort())
  db.exec(readFileSync(`${SRC}/${f}`, 'utf8'));

const objs = db
  .prepare(`SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY rowid`)
  .all();
const stmt = (sql) => `${sql.trim()};\n`;

const header = (what) =>
  `-- ${what}: baseline equal to D1 migrations 0001–${UPTO}, generated by tools/db/split-baseline.mjs. Forward-only\n` +
  `-- and expand-only from here (docs/multi-user.md 5.7): add tables, columns and indexes; never drop or rename what\n` +
  `-- the previous release still reads.\n\n`;

let dir = header('Directory (one Durable Object)');
// The Directory's own view of a budget: just what membership and People need. Money fields live in the store.
dir += stmt(`CREATE TABLE budget (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
)`);
let store = header('BudgetStore (one Durable Object per budget)');
for (const o of objs) {
  const isDir = DIRECTORY.has(o.tbl_name);
  if (isDir) dir += stmt(o.sql);
  else store += stmt(o.sql);
  if (o.type === 'table' && o.name === 'apply_counter')
    store += stmt('INSERT INTO apply_counter (id, seq) VALUES (1, 0)');
}

mkdirSync('packages/db/directory-migrations', { recursive: true });
mkdirSync('packages/db/budget-migrations', { recursive: true });
writeFileSync('packages/db/directory-migrations/0001_baseline.sql', dir);
writeFileSync('packages/db/budget-migrations/0001_baseline.sql', store);
console.log('wrote directory and budget baselines');
